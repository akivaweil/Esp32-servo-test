#include <Arduino.h>

// Forward declarations
void initializeOTA();
void updateOTA();

//╔═══╗ ════════════════════════════════════════════════════════════════ ╔═══╗
//║ 🚀 SETUP                                                              ║
//╚═══╝ ════════════════════════════════════════════════════════════════ ╚═══╝

void setup() {
    Serial.begin(115200);
    delay(1000);
    
    // Initialize OTA
    initializeOTA();
}

//╔═══╗ ════════════════════════════════════════════════════════════════ ╔═══╗
//║ 🔄 LOOP                                                               ║
//╚═══╝ ════════════════════════════════════════════════════════════════ ╚═══╝

void loop() {
    // Update OTA
    updateOTA();
    
    delay(10);
}

